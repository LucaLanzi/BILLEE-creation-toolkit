def _gazebo_xacro(robot, package: str) -> str:
    ET.register_namespace("xacro", XACRO_NS)
    root = ET.Element("robot", {"name": robot.name})
    ET.SubElement(root, f"{{{XACRO_NS}}}include", {"filename": "assembly.urdf.xacro"})
    control = ET.SubElement(root, "ros2_control", {"name": "IgnitionSystem", "type": "system"})
    hardware = ET.SubElement(control, "hardware")
    ET.SubElement(hardware, "plugin").text = "ign_ros2_control/IgnitionSystem"
    for joint in sorted(robot.joints, key=lambda j: j.name):
        if joint.type is JointType.FIXED:
            continue
        node = ET.SubElement(control, "joint", {"name": joint.name})
        if joint.actuation is Actuation.ACTUATED:
            command = "velocity" if joint.role is ControlRole.BASE_DRIVE else "position"
            ET.SubElement(node, "command_interface", {"name": command})
        ET.SubElement(node, "state_interface", {"name": "position"})
        ET.SubElement(node, "state_interface", {"name": "velocity"})
    gazebo = ET.SubElement(root, "gazebo")
    plugin = ET.SubElement(gazebo, "plugin", {
        "filename": "libign_ros2_control-system.so", "name": "ign_ros2_control::IgnitionROS2ControlPlugin",
    })
    ET.SubElement(plugin, "parameters").text = f"$(find {package})/config/ros2_controllers.yaml"
    ET.indent(root, space="  ")
    return '<?xml version="1.0"?>\n' + ET.tostring(root, encoding="unicode") + "\n"


def _yaml_list(values: list[str], indent: str) -> str:
    return "\n".join(f"{indent}- {v}" for v in values) if values else f"{indent}[]"


def _controllers(robot, arm: list[str]) -> tuple[str, list[str]]:
    wheels = [
        j.name for j in sorted(robot.joints, key=lambda j: j.name)
        if j.role is ControlRole.BASE_DRIVE and j.actuation is Actuation.ACTUATED
    ]
    names = ["joint_state_broadcaster"]
    head = "controller_manager:\n  ros__parameters:\n    update_rate: 100\n    use_sim_time: true\n"
    head += "    joint_state_broadcaster:\n      type: joint_state_broadcaster/JointStateBroadcaster\n"
    tail = ""
    if arm:
        names.append("arm_controller")
        head += "    arm_controller:\n      type: joint_trajectory_controller/JointTrajectoryController\n"
        tail += ("arm_controller:\n  ros__parameters:\n    joints:\n" + _yaml_list(arm, "      ") +
                 "\n    command_interfaces:\n      - position\n    state_interfaces:\n      - position\n      - velocity\n")
    if wheels:
        names.append("wheel_controller")
        head += "    wheel_controller:\n      type: velocity_controllers/JointGroupVelocityController\n"
        tail += "wheel_controller:\n  ros__parameters:\n    joints:\n" + _yaml_list(wheels, "      ") + "\n"
    return head + tail, names


def _moveit_files(robot, arm: list[str]) -> dict[str, str]:
    by_name = {j.name: j for j in robot.joints}
    limits = "joint_limits:\n"
    for name in arm:
        joint = by_name[name]
        limits += f"  {name}:\n    has_velocity_limits: true\n    max_velocity: {joint.limit.velocity}\n"
        limits += "    has_acceleration_limits: false\n    max_acceleration: 0.0\n"
    controllers = (
        "moveit_controller_manager: moveit_simple_controller_manager/MoveItSimpleControllerManager\n"
        "moveit_simple_controller_manager:\n  controller_names:\n    - arm_controller\n"
        "  arm_controller:\n    type: FollowJointTrajectory\n    action_ns: follow_joint_trajectory\n"
        "    default: true\n    joints:\n" + _yaml_list(arm, "      ") + "\n"
    )
    kinematics = (
        "# Intentionally empty. The demo uses joint-space goals. A two-joint arm cannot\n"
        "# reach arbitrary 6D poses, so no Cartesian IK solver is configured.\n{}\n"
    )
    return {
        "config/moveit/joint_limits.yaml": limits,
        "config/moveit/moveit_controllers.yaml": controllers,
        "config/moveit/kinematics.yaml": kinematics,
    }


def _readme(package: str, robot: str) -> str:
    return f"""# {package}

Generated by Rover & Arm Builder. Dimensions and physical values are authoring estimates.
Target stack: ROS 2 Humble with Gazebo Fortress and `ign_ros2_control`.

    mkdir -p ~/ros_ws/src && cp -r {package} ~/ros_ws/src/
    cd ~/ros_ws && colcon build --packages-select {package} && source install/setup.bash
    ros2 launch {package} display.launch.py
    ros2 launch {package} gazebo.launch.py

`config/moveit/` holds a starting SRDF and limits for the MoveIt Setup Assistant. For the BILLEE rover
and arm, use the BILLEE export instead.

Models in `urdf/`: `{robot}.urdf` (plain), `assembly.urdf.xacro`, one `standalone_*.urdf.xacro` per
module, and `gazebo.urdf.xacro` (simulator-specific additions).

Put your own files in `config/user/`. Regeneration never changes that folder. Any other generated
file you edit makes the next export stop and list the conflict rather than overwrite your change.
"""


def spawn_height(robot, clearance: float = 0.02) -> float:
    """Height that places the lowest zero-pose collision shape just above the ground."""
    by_child = {j.child: j for j in robot.joints}

    def link_pose(name: str) -> Transform:
        joint = by_child.get(name)
        return Transform() if joint is None else link_pose(joint.parent) @ joint.origin

    lowest = None
    for link in robot.links:
        pose = link_pose(link.name)
        for item in link.collisions:
            world = pose @ item.origin
            if isinstance(item.shape, Mesh):
                bottom = min(world.apply(p)[2] for tri in item.shape.triangles for p in tri)
            else:
                bottom = world.t[2] - shape_half_extents(item.shape, world.R)[2]
            lowest = bottom if lowest is None else min(lowest, bottom)
    return round(max(0.0, -(lowest or 0.0)) + clearance, 4)


def build_files(project: Project, package: str, target: Target = Target.VISUALIZATION) -> tuple[dict[str, bytes], object]:
    """Validate and return {relative path: content}. Nothing is written."""
    if not PACKAGE_RE.match(package):
        raise ValueError(f"Package name {package!r} must be lowercase letters, digits, and underscores.")
    module_ids = [m.id for m in project.modules]
    report = validate_project(project, module_ids)
    if not report.ok(target):
        raise ExportBlocked(target, report.blockers(target))
    robot = report.robot

    text: dict[str, str] = {
        "package.xml": _package_xml(package),
        "CMakeLists.txt": _cmake(package),
        "README.md": _readme(package, robot.name),
        "rviz/display.rviz": _rviz(robot.root),
        f"urdf/{robot.name}.urdf": robot_to_urdf(robot, package),
        "urdf/assembly.urdf.xacro": top_level_xacro(project, robot.name, module_ids),
    }
    for module in project.modules:
        text[f"urdf/{module_filename(module)}"] = module_macro_xml(module, package)
        stem = re.sub(r"\W", "_", module.name.lower())
        text[f"urdf/standalone_{stem}.urdf.xacro"] = top_level_xacro(project, f"{robot.name}_{stem}", [module.id])

    arm = arm_joint_names(project, robot, module_ids)
    controllers, controller_names = _controllers(robot, arm)
    text["urdf/gazebo.urdf.xacro"] = _gazebo_xacro(robot, package)
    text["config/ros2_controllers.yaml"] = controllers
    text["config/moveit/robot.srdf"] = robot_to_srdf(project, robot, module_ids)
    text.update(_moveit_files(robot, arm))
    spawn_z = fmt(spawn_height(robot))
    substitute = lambda s: (
        s.replace("@PACKAGE@", package).replace("@ROBOT@", robot.name)
        .replace("@CONTROLLERS@", repr(controller_names)).replace("@SPAWN_Z@", spawn_z)
    )
    text["launch/display.launch.py"] = substitute(_DISPLAY_LAUNCH)
    text["launch/gazebo.launch.py"] = substitute(_GAZEBO_LAUNCH)
    text["meshes/.gitkeep"] = ""

    files = {path: content.encode("utf-8") for path, content in text.items()}
    for link in robot.links:
        for item in [*link.visuals, *link.collisions]:
            if isinstance(item.shape, Mesh):
                files[f"meshes/{mesh_filename(item.shape.asset)}"] = mesh_to_stl_bytes(item.shape)
    return dict(sorted(files.items())), report


def _digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def write_package(project: Project, destination: str | os.PathLike, package: str,
                  target: Target = Target.VISUALIZATION) -> tuple[Path, object]:
    """Write to a staging folder first, then update the destination."""
    files, report = build_files(project, package, target)
    dest = Path(destination)
    manifest_path = dest / MANIFEST
    previous: dict[str, str] = {}

    if dest.exists() and any(dest.iterdir()):
        if not manifest_path.is_file():
            raise PackageConflict(f"{dest} is not empty and was not generated by this tool.")
        previous = json.loads(manifest_path.read_text(encoding="utf-8"))["files"]
        edited = sorted(
            rel for rel, digest in previous.items()
            if (dest / rel).is_file() and _digest((dest / rel).read_bytes()) != digest
        )
        if edited:
            raise PackageConflict("These generated files were edited: " + ", ".join(edited))
        unrelated = sorted(
            rel for rel in files
            if rel not in previous and (dest / rel).exists()
        )
        if unrelated:
            raise PackageConflict("These existing files are not managed by this tool: " + ", ".join(unrelated))

    dest.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=f".{dest.name}.staging-", dir=dest.parent))
    try:
        for rel, data in files.items():
            path = staging / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        manifest = {"generator": "rover_arm_builder", "files": {r: _digest(d) for r, d in files.items()}}
        (staging / MANIFEST).write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")

        dest.mkdir(parents=True, exist_ok=True)
        for rel in files:
            target_path = dest / rel
            target_path.parent.mkdir(parents=True, exist_ok=True)
            os.replace(staging / rel, target_path)
        for rel in set(previous) - set(files):
            stale = dest / rel
            if stale.is_file():
                stale.unlink()
        os.replace(staging / MANIFEST, manifest_path)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return dest, report
