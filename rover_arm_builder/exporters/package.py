MANIFEST = ".rab_manifest.json"
PACKAGE_RE = re.compile(r"^[a-z][a-z0-9_]*$")


class PackageConflict(RuntimeError):
    """The destination holds content this export must not overwrite."""


def _package_xml(package: str) -> str:
    depends = [
        "robot_state_publisher", "joint_state_publisher_gui", "rviz2", "xacro", "ros_gz_sim", "ros_gz_bridge",
        "ign_ros2_control", "controller_manager", "joint_state_broadcaster", "joint_trajectory_controller",
        "velocity_controllers",
    ]
    lines = "\n".join(f"  <exec_depend>{d}</exec_depend>" for d in depends)
    return f"""<?xml version="1.0"?>
<package format="3">
  <name>{package}</name>
  <version>0.1.0</version>
  <description>Robot description generated by Rover &amp; Arm Builder.</description>
  <maintainer email="maintainer@example.invalid">Package maintainer</maintainer>
  <license>Apache-2.0</license>
  <buildtool_depend>ament_cmake</buildtool_depend>
{lines}
  <export><build_type>ament_cmake</build_type></export>
</package>
"""


def _cmake(package: str) -> str:
    return f"""cmake_minimum_required(VERSION 3.16)
project({package} NONE)
find_package(ament_cmake REQUIRED)
install(DIRECTORY urdf meshes launch rviz config DESTINATION share/${{PROJECT_NAME}})
ament_package()
"""


