"""Portable ROS 2 description package generation with staged, protected writes.

Generated files are tracked by hash in `.rab_manifest.json`. A file edited by the user,
or an existing folder this tool did not generate, stops the export instead of being
overwritten. Anything under `config/user/` is never touched.
"""

